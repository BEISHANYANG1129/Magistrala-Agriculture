const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { chromium } = require(path.join(__dirname, '../../../magistrala-ui/node_modules/@playwright/test'))

async function main() {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(pathToFileURL(path.join(__dirname, 'qa-assistant-flow-viewer.html')).href)
    await page.waitForFunction(() => document.getElementById('diagram').naturalWidth > 0)
    const initial = await page.locator('#zoom-label').textContent()
    await page.locator('#zoom-in').click()
    const enlarged = await page.locator('#zoom-label').textContent()
    if (parseInt(enlarged) <= parseInt(initial)) throw new Error('Zoom in failed')
    const before = await page.locator('#diagram').getAttribute('style')
    await page.mouse.move(700, 400)
    await page.mouse.down()
    await page.mouse.move(820, 500)
    await page.mouse.up()
    const after = await page.locator('#diagram').getAttribute('style')
    if (after === before) throw new Error('Pan failed')
    await page.locator('#fit-all').click()
    const overview = await page.locator('#zoom-label').textContent()
    if (parseInt(overview) >= parseInt(enlarged)) throw new Error('Fit all failed')
    await page.screenshot({ path: path.join(__dirname, 'viewer-preview.png') })
    await page.locator('#actual-size').click()
    if ((await page.locator('#zoom-label').textContent()) !== '100%') throw new Error('Actual size failed')
    await page.mouse.move(600, 400)
    await page.mouse.wheel(0, 250)
    await page.waitForTimeout(100)
    if (parseInt(await page.locator('#zoom-label').textContent()) >= 100) throw new Error('Wheel zoom failed')
    await page.goto(pathToFileURL(path.join(__dirname, 'qa-assistant-flow.svg')).href)
    if (await page.locator('foreignObject').count()) throw new Error('SVG uses nonportable HTML labels')
    const labels = await page.locator('text').count()
    if (labels < 34) throw new Error('Missing SVG text labels')
    if (errors.length) throw new Error(errors.join('; '))
    console.log(JSON.stringify({ initial, enlarged, overview, svgTextLabels: labels, pan: true, wheelZoom: true, standaloneSvg: true }))
  } finally {
    await browser.close()
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1 })
