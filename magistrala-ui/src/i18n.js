export function label(name) {
  if (language.value === 'zh' && words[name]) return words[name]
  const text = String(name)
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/[_-]/g, ' ')
  if (language.value === 'en') return text.charAt(0).toUpperCase() + text.slice(1)
  return text
    .split(' ')
    .map((w) => words[w] || words[w.toLowerCase()] || w)
    .join(' ')
}
